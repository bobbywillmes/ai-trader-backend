import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import 'dotenv/config';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { Client } from 'pg';
import { PrismaClient } from '@prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
import { createDisposablePostgresDatabase, type DisposablePostgresDatabase } from './disposable-postgres.js';

const enabled = process.env.RUN_DATABASE_INTEGRITY_TESTS === '1' && process.env.DATABASE_URL;
const describeDatabase = enabled ? describe : describe.skip;
const migrationPath = 'prisma/migrations/20261017120000_add_entry_exposure_claims/migration.sql';
const stateGuardMigrationPath = 'prisma/migrations/20261017130000_guard_entry_exposure_claim_states/migration.sql';

describeDatabase('entry exposure claim database integrity', () => {
  const schema = `entry_claim_${randomUUID().replaceAll('-', '')}`;
  const quotedSchema = `"${schema}"`;
  let disposable: DisposablePostgresDatabase;
  let admin: Client;
  let accountA: number;
  let accountB: number;
  let spy: number;
  let qqq: number;

  beforeAll(async () => {
    disposable = await createDisposablePostgresDatabase(process.env.DATABASE_URL!, 'entry_claim');
    await disposable.migrate();
    await disposable.verify();
    admin = new Client({ connectionString: disposable.url });
    await admin.connect();
    await admin.query(`CREATE SCHEMA ${quotedSchema}`);
    await admin.query(`SET search_path TO ${quotedSchema}`);
    await admin.query(`
      CREATE TABLE "TradingAccount" ("id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
      CREATE TABLE "Security" ("id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "symbol" text NOT NULL UNIQUE);
      CREATE TABLE "OrderIntent" ("id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
      CREATE TABLE "TrackedPosition" ("id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
    `);
    accountA = Number((await admin.query('INSERT INTO "TradingAccount" DEFAULT VALUES RETURNING id')).rows[0].id);
    accountB = Number((await admin.query('INSERT INTO "TradingAccount" DEFAULT VALUES RETURNING id')).rows[0].id);
    spy = Number((await admin.query(`INSERT INTO "Security" (symbol) VALUES ('SPY') RETURNING id`)).rows[0].id);
    qqq = Number((await admin.query(`INSERT INTO "Security" (symbol) VALUES ('QQQ') RETURNING id`)).rows[0].id);
    await admin.query(await readFile(migrationPath, 'utf8'));
    await admin.query(await readFile(stateGuardMigrationPath, 'utf8'));
  });

  afterAll(async () => {
    await admin?.query(`DROP SCHEMA IF EXISTS ${quotedSchema} CASCADE`);
    await admin?.end();
    await disposable?.drop();
  });

  async function client() {
    const value = new Client({ connectionString: disposable.url });
    await value.connect();
    await value.query(`SET search_path TO ${quotedSchema}`);
    return value;
  }

  function prismaClient() {
    return new PrismaClient({ adapter: new PrismaPg({ connectionString: disposable.url }) });
  }

  async function intent(db: Client) {
    return Number((await db.query('INSERT INTO "OrderIntent" DEFAULT VALUES RETURNING id')).rows[0].id);
  }

  async function claim(db: Client, values: { accountId: number; securityId: number; intentId: number; ownerKey: string }) {
    return db.query(`
      INSERT INTO "EntryExposureClaim"
        ("tradingAccountId", "securityId", "orderIntentId", "ownerKey", "updatedAt")
      VALUES ($1, $2, $3, $4, CURRENT_TIMESTAMP)
      RETURNING id
    `, [values.accountId, values.securityId, values.intentId, values.ownerKey]);
  }

  it('allows only one concurrent unreleased owner for one account and security', async () => {
    const first = await client();
    const second = await client();
    try {
      const firstIntent = await intent(first);
      const secondIntent = await intent(second);
      const results = await Promise.allSettled([
        claim(first, { accountId: accountA, securityId: spy, intentId: firstIntent, ownerKey: 'concurrent:first' }),
        claim(second, { accountId: accountA, securityId: spy, intentId: secondIntent, ownerKey: 'concurrent:second' }),
      ]);
      expect(results.filter((result) => result.status === 'fulfilled')).toHaveLength(1);
      expect(results.filter((result) => result.status === 'rejected')).toHaveLength(1);
      expect(String(results.find((result) => result.status === 'rejected')?.reason)).toContain('EntryExposureClaim_active_account_security_key');
    } finally {
      await first.end();
      await second.end();
    }
  });

  it('keeps symbols and PAPER/LIVE account identities independent', async () => {
    const db = await client();
    try {
      await claim(db, { accountId: accountA, securityId: qqq, intentId: await intent(db), ownerKey: 'independent:qqq' });
      await claim(db, { accountId: accountB, securityId: spy, intentId: await intent(db), ownerKey: 'independent:other-account' });
    } finally {
      await db.end();
    }
  });

  it('permits a new lifecycle only after an explicit durable release', async () => {
    const db = await client();
    try {
      await db.query(`UPDATE "EntryExposureClaim" SET status='RELEASED', "releasedAt"=CURRENT_TIMESTAMP, "releaseReason"='TEST_CONFIRMED_TERMINAL', "updatedAt"=CURRENT_TIMESTAMP WHERE "tradingAccountId"=$1 AND "securityId"=$2 AND "releasedAt" IS NULL`, [accountA, spy]);
      await claim(db, { accountId: accountA, securityId: spy, intentId: await intent(db), ownerKey: 'after-release' });
    } finally {
      await db.end();
    }
  });

  it('rolls claim ownership back with its admission transaction', async () => {
    const db = await client();
    try {
      await db.query('BEGIN');
      await claim(db, { accountId: accountB, securityId: qqq, intentId: await intent(db), ownerKey: 'rolled-back' });
      await db.query('ROLLBACK');
      const rows = await db.query(`SELECT id FROM "EntryExposureClaim" WHERE "ownerKey"='rolled-back'`);
      expect(rows.rowCount).toBe(0);
      await claim(db, { accountId: accountB, securityId: qqq, intentId: await intent(db), ownerKey: 'after-rollback' });
    } finally {
      await db.end();
    }
  });

  it('rejects unknown states and inconsistent release markers at the database boundary', async () => {
    const db = await client();
    try {
      const guardAccount = Number((await db.query('INSERT INTO "TradingAccount" DEFAULT VALUES RETURNING id')).rows[0].id);
      const claimId = Number((await claim(db, {
        accountId: guardAccount, securityId: spy, intentId: await intent(db), ownerKey: 'state-guard',
      })).rows[0].id);
      await expect(db.query(`UPDATE "EntryExposureClaim" SET status='FUTURE_UNSAFE', "updatedAt"=CURRENT_TIMESTAMP WHERE id=$1`, [claimId]))
        .rejects.toThrow(/EntryExposureClaim_status_check/);
      await expect(db.query(`UPDATE "EntryExposureClaim" SET "releasedAt"=CURRENT_TIMESTAMP, "releaseReason"='unsafe', "updatedAt"=CURRENT_TIMESTAMP WHERE id=$1`, [claimId]))
        .rejects.toThrow(/EntryExposureClaim_released_status_check/);
    } finally {
      await db.end();
    }
  });

  it('prevents a stale compare-and-set observation from overwriting UNRESOLVED', async () => {
    const observer = await client();
    const resolver = await client();
    try {
      const casAccount = Number((await observer.query('INSERT INTO "TradingAccount" DEFAULT VALUES RETURNING id')).rows[0].id);
      const claimId = Number((await claim(observer, {
        accountId: casAccount, securityId: spy, intentId: await intent(observer), ownerKey: 'cas-stale-observation',
      })).rows[0].id);
      const observed = String((await observer.query('SELECT status FROM "EntryExposureClaim" WHERE id=$1', [claimId])).rows[0].status);
      await resolver.query(`UPDATE "EntryExposureClaim" SET status='UNRESOLVED', "updatedAt"=CURRENT_TIMESTAMP WHERE id=$1`, [claimId]);
      const stale = await observer.query(`
        UPDATE "EntryExposureClaim"
        SET status='BROKER_ORDER_ACTIVE', "updatedAt"=CURRENT_TIMESTAMP
        WHERE id=$1 AND status=$2 AND "releasedAt" IS NULL
      `, [claimId, observed]);
      expect(stale.rowCount).toBe(0);
      expect((await observer.query('SELECT status FROM "EntryExposureClaim" WHERE id=$1', [claimId])).rows[0].status).toBe('UNRESOLVED');
    } finally {
      await observer.end();
      await resolver.end();
    }
  });

  const itPrisma = process.env.RUN_ENTRY_EXPOSURE_PRISMA_TESTS === '1' ? it : it.skip;
  itPrisma('enforces ownership and stale-transition CAS through real Prisma transactions', async () => {
    const first = prismaClient();
    const second = prismaClient();
    const suffix = randomUUID();
    try {
      const user = await first.user.create({ data: { email: `entry-claim-${suffix}@example.invalid` } });
      const account = await first.tradingAccount.create({ data: { accountHolderUserId: user.id, displayName: `Entry Claim ${suffix}` } });
      const security = await first.security.create({ data: { symbol: `T${suffix.replaceAll('-', '').slice(0, 8)}`, name: 'Disposable claim test', assetType: 'STOCK' } });
      const intentData = (clientOrderId: string) => ({
        source: 'integration_test', symbol: security.symbol, side: 'buy', orderType: 'market', timeInForce: 'day',
        clientOrderId, rawRequestJson: {}, tradingAccountId: account.id,
      });
      const firstIntent = await first.orderIntent.create({ data: intentData(`first-${suffix}`) });
      const secondIntent = await first.orderIntent.create({ data: intentData(`second-${suffix}`) });
      const create = (db: PrismaClient, intentId: number, ownerKey: string) => db.$transaction(async (tx) => {
        await tx.$queryRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`entry-exposure:${account.id}:${security.id}`}, 0))::text`;
        return tx.entryExposureClaim.create({ data: {
          tradingAccountId: account.id, securityId: security.id, orderIntentId: intentId, ownerKey,
        } });
      });
      const results = await Promise.allSettled([
        create(first, firstIntent.id, `prisma-owner:first:${suffix}`),
        create(second, secondIntent.id, `prisma-owner:second:${suffix}`),
      ]);
      expect(results.filter((result) => result.status === 'fulfilled')).toHaveLength(1);
      const winner = results.find((result): result is PromiseFulfilledResult<Awaited<ReturnType<typeof create>>> => result.status === 'fulfilled')!.value;
      await first.entryExposureClaim.update({ where: { id: winner.id }, data: { status: 'UNRESOLVED' } });
      const stale = await second.entryExposureClaim.updateMany({
        where: { id: winner.id, status: 'ENTRY_PENDING', releasedAt: null },
        data: { status: 'BROKER_ORDER_ACTIVE' },
      });
      expect(stale.count).toBe(0);
      expect((await first.entryExposureClaim.findUniqueOrThrow({ where: { id: winner.id } })).status).toBe('UNRESOLVED');
    } finally {
      await first.$disconnect();
      await second.$disconnect();
    }
  });
});
